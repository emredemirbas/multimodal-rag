from typing import Protocol
from uuid import UUID

import boto3
from botocore.config import Config
from botocore.exceptions import BotoCoreError, ClientError

from ..config import Settings
from ..sources.contracts import SourceError


def object_prefix(tenant_id: str, project_id: UUID, source_id: UUID | None = None) -> str:
    prefix = f'{tenant_id}/{project_id}/'
    return prefix if source_id is None else f'{prefix}{source_id}/'


class ArtifactStore(Protocol):
    def put(self, key: str, content: bytes) -> None: ...
    def get(self, key: str, limit: int) -> bytes: ...
    def delete_prefix(self, prefix: str) -> None: ...


class S3ArtifactStore:
    def __init__(self, settings: Settings):
        if not settings.s3_access_key or not settings.s3_secret_key:
            raise SourceError('storage_not_configured', 'Transcript storage is not configured.', 503)
        self.bucket = settings.s3_bucket
        self.client = boto3.client(
            's3', endpoint_url=settings.s3_endpoint, region_name='us-east-1',
            aws_access_key_id=settings.s3_access_key, aws_secret_access_key=settings.s3_secret_key,
            config=Config(connect_timeout=3, read_timeout=5,
                          retries={'total_max_attempts': 2, 'mode': 'standard'},
                          s3={'addressing_style': 'path'}),
        )

    def ensure_bucket(self) -> None:
        try:
            self.client.head_bucket(Bucket=self.bucket)
        except ClientError as exc:
            if str(exc.response.get('Error', {}).get('Code')) not in {'404', 'NoSuchBucket', 'NotFound'}:
                raise self._unavailable() from None
            try:
                self.client.create_bucket(Bucket=self.bucket)
            except ClientError as create_exc:
                if create_exc.response.get('Error', {}).get('Code') not in {'BucketAlreadyOwnedByYou', 'BucketAlreadyExists'}:
                    raise self._unavailable() from None
        except BotoCoreError:
            raise self._unavailable() from None

    @staticmethod
    def _unavailable() -> SourceError:
        return SourceError('storage_unavailable', 'Storage is temporarily unavailable; retry shortly.', 503, transient=True)

    def put(self, key: str, content: bytes) -> None:
        try:
            self.ensure_bucket()
            content_type = 'audio/wav' if key.endswith('/input.wav') else 'text/plain; charset=utf-8'
            if key.endswith('/input.mp4'):
                content_type = 'video/mp4'
            if key.endswith('/frame.png'):
                content_type = 'image/png'
            self.client.put_object(Bucket=self.bucket, Key=key, Body=content, ContentType=content_type)
        except (ClientError, BotoCoreError):
            raise self._unavailable() from None

    def get(self, key: str, limit: int) -> bytes:
        try:
            response = self.client.get_object(Bucket=self.bucket, Key=key)
            with response['Body'] as body:
                content = body.read(limit + 1)
            if len(content) > limit:
                raise SourceError('invalid_artifact', 'The stored artifact exceeds its size limit.')
            return content
        except (ClientError, BotoCoreError):
            raise self._unavailable() from None

    def delete_prefix(self, prefix: str) -> None:
        # Prefixes are generated by the application; callers never supply them.
        if prefix.count('/') < 2 or not prefix.endswith('/'):
            raise ValueError('unsafe artifact cleanup prefix')
        try:
            # Repeatedly consume the first page; deleting changes pagination.
            for _ in range(100):
                objects = self.client.list_objects_v2(Bucket=self.bucket, Prefix=prefix, MaxKeys=1000).get('Contents', [])
                if not objects:
                    return
                result = self.client.delete_objects(Bucket=self.bucket, Delete={'Objects': [{'Key': obj['Key']} for obj in objects], 'Quiet': True})
                if result.get('Errors'):
                    raise self._unavailable()
            raise self._unavailable()
        except ClientError as exc:
            if exc.response.get('Error', {}).get('Code') == 'NoSuchBucket':
                return
            raise self._unavailable() from None
        except BotoCoreError:
            raise self._unavailable() from None
